def svg(name: str, size: str = "md", label: str = "") -> str:
    """An icon that points at the page's sprite (see `sprite`), so server and browser share one set."""
    px = SIZES.get(size, SIZES["md"])
    if name not in ICONS:
        raise KeyError(f"unknown icon {name!r}")
    a11y = f'role="img" aria-label="{label}"' if label else 'aria-hidden="true" focusable="false"'
    return f'<svg class="icon icon--{size}" width="{px}" height="{px}" {PAINT} {a11y}><use href="#i-{name}"></use></svg>'


def sprite() -> str:
    """Every icon as a <symbol>, rendered once per page in base.html."""
    symbols = "".join(
        f'<symbol id="i-{name}" viewBox="0 0 24 24">{paths}</symbol>'
        for name, paths in ICONS.items()
    )
    return f'<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">{symbols}</svg>'

